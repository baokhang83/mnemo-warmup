package io.github.baokhang83.mnemo.warmup.core;

import java.io.IOException;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.attribute.BasicFileAttributes;
import java.nio.file.attribute.PosixFilePermission;
import java.util.EnumSet;

/**
 * A unique per-run directory on a pre-provisioned shared volume. The training pod should receive
 * only this directory as a subPath, while the publisher uses a separate, private upload copy.
 * The claim root must be restricted to the trusted coordinator and its configured training pods.
 */
public final class IsolatedHandoff implements AutoCloseable {
    private static final int MAX_CLEANUP_ENTRIES = 10_000;
    private static final int MAX_CLEANUP_DEPTH = 32;
    private final Path directory;

    private IsolatedHandoff(Path directory) { this.directory = directory; }

    /**
     * Creates a group-writable directory. Kubernetes fsGroup should own the claim root and include
     * both the coordinator and training process; filesystems without POSIX permissions are refused.
     */
    public static IsolatedHandoff create(Path claimRoot) throws IOException {
        Path root = claimRoot.toAbsolutePath().normalize();
        if (!Files.isDirectory(root, LinkOption.NOFOLLOW_LINKS)) {
            throw new IOException("handoff root is missing or is not a directory");
        }
        Path dir = Files.createTempDirectory(root, "mnemo-run-");
        boolean ready = false;
        try {
            Object parentGroup = Files.getAttribute(root, "unix:gid", LinkOption.NOFOLLOW_LINKS);
            Object actualGroup = Files.getAttribute(dir, "unix:gid", LinkOption.NOFOLLOW_LINKS);
            if (!parentGroup.equals(actualGroup)) {
                Files.setAttribute(dir, "unix:gid", parentGroup, LinkOption.NOFOLLOW_LINKS);
            }
            if (!parentGroup.equals(Files.getAttribute(dir, "unix:gid", LinkOption.NOFOLLOW_LINKS))) {
                throw new IOException("handoff directory did not inherit the claim group");
            }
            Files.setPosixFilePermissions(dir, EnumSet.of(
                    PosixFilePermission.OWNER_READ, PosixFilePermission.OWNER_WRITE, PosixFilePermission.OWNER_EXECUTE,
                    PosixFilePermission.GROUP_READ, PosixFilePermission.GROUP_WRITE, PosixFilePermission.GROUP_EXECUTE));
            ready = true;
            return new IsolatedHandoff(dir);
        } catch (UnsupportedOperationException e) {
            throw new IOException("handoff requires a POSIX filesystem supporting group ownership", e);
        } finally {
            if (!ready) Files.deleteIfExists(dir);
        }
    }

    /** Safe relative subPath for the child pod, generated by the coordinator. */
    public String name() { return directory.getFileName().toString(); }

    /** Coordinator-side path; the training pod sees this directory as its own mount root. */
    public Path directory() { return directory; }

    /**
     * Deletes this run's handoff without following links. Only call after the training pod has
     * stopped and cannot write the volume. Refuses excessive depth or entries rather than walking
     * an unbounded attacker-controlled tree. A failure requires operator cleanup.
     */
    @Override public void close() throws IOException {
        if (!Files.exists(directory, LinkOption.NOFOLLOW_LINKS)) return;
        int[] entries = {0};
        Files.walkFileTree(directory, EnumSet.noneOf(java.nio.file.FileVisitOption.class), MAX_CLEANUP_DEPTH,
                new SimpleFileVisitor<>() {
                    private void count() throws IOException {
                        if (++entries[0] > MAX_CLEANUP_ENTRIES) throw new IOException("handoff cleanup entry limit exceeded");
                    }
                    @Override public FileVisitResult preVisitDirectory(Path dir, BasicFileAttributes attrs) throws IOException {
                        count();
                        return FileVisitResult.CONTINUE;
                    }
                    @Override public FileVisitResult visitFile(Path file, BasicFileAttributes attrs) throws IOException {
                        count();
                        if (attrs.isDirectory()) throw new IOException("handoff cleanup depth limit exceeded");
                        Files.delete(file);
                        return FileVisitResult.CONTINUE;
                    }
                    @Override public FileVisitResult postVisitDirectory(Path dir, IOException error) throws IOException {
                        if (error != null) throw error;
                        Files.delete(dir);
                        return FileVisitResult.CONTINUE;
                    }
                });
    }
}
